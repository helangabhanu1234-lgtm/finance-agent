"""Tool: generate_report - writes a self-contained HTML report (inline SVG chart, no extra libraries)."""
from html import escape

import config
from tools.budget_tools import check_budget
from tools.expense_tools import get_expenses, summarize_spending
from tools.validators import parse_month

_CSS = """
body{background:#0b0b0b;color:#eee;font-family:Segoe UI,Arial,sans-serif;margin:0;padding:32px;max-width:900px;margin:auto}
h1{color:#e10600;border-bottom:3px solid #e10600;padding-bottom:8px}h2{color:#ff3b30;margin-top:32px}
table{border-collapse:collapse;width:100%}th{background:#e10600;color:#fff;text-align:left;padding:8px}
td{border-bottom:1px solid #333;padding:8px}.num{text-align:right}.kpi{font-size:28px;color:#fff}
.OK{color:#4caf50}.WARNING{color:#ffb300}.OVER{color:#ff3b30;font-weight:bold}small{color:#888}
"""


def _bar_chart(items) -> str:
    if not items:
        return "<p>No spending recorded.</p>"
    row_h, label_w, chart_w = 28, 130, 520
    peak = max(i["total_lkr"] for i in items) or 1
    parts = [f'<svg width="{label_w + chart_w + 120}" height="{row_h * len(items) + 10}" role="img" aria-label="Spending by category">']
    for idx, item in enumerate(items):
        y = idx * row_h + 4
        width = max(2, int(chart_w * item["total_lkr"] / peak))
        parts.append(f'<text x="0" y="{y + 17}" fill="#ddd" font-size="13">{escape(item["category"])}</text>')
        parts.append(f'<rect x="{label_w}" y="{y}" width="{width}" height="20" fill="#e10600" rx="3"/>')
        parts.append(f'<text x="{label_w + width + 8}" y="{y + 15}" fill="#ddd" font-size="12">{item["total_lkr"]:,.0f}</text>')
    parts.append("</svg>")
    return "".join(parts)


def generate_report(month=None) -> dict:
    start, _ = parse_month(month)
    label = f"{start:%Y-%m}"
    summary = summarize_spending(month=label)
    budgets = check_budget(month=label)
    recent = get_expenses(month=label, limit=15)

    rows = "".join(
        f"<tr><td>{escape(e['date'])}</td><td>{escape(e['category'])}</td><td>{escape(e['description'])}</td>"
        f"<td class='num'>{e['amount_lkr']:,.2f}</td></tr>" for e in recent["expenses"]
    ) or "<tr><td colspan='4'>No transactions.</td></tr>"
    budget_rows = "".join(
        f"<tr><td>{escape(b['category'])}</td><td class='num'>{b['limit_lkr']:,.0f}</td>"
        f"<td class='num'>{b['spent_lkr']:,.0f}</td><td class='num'>{b['percent_used']}%</td>"
        f"<td class='{b['status']}'>{b['status']}</td></tr>" for b in budgets["budgets"]
    ) or "<tr><td colspan='5'>No budgets set.</td></tr>"

    html = f"""<!doctype html><html><head><meta charset="utf-8"><title>Finance report {label}</title>
<style>{_CSS}</style></head><body>
<h1>Personal Finance Report - {start:%B %Y}</h1>
<p class="kpi">Total spent: Rs. {summary['total_lkr']:,.2f}</p>
<p>{summary['transactions']} transactions &middot; top category: {escape(str(summary['top_category']))}</p>
<h2>Spending by category</h2>{_bar_chart(summary['by_category'])}
<h2>Budget status</h2>
<table><tr><th>Category</th><th>Limit</th><th>Spent</th><th>Used</th><th>Status</th></tr>{budget_rows}</table>
<h2>Latest transactions</h2>
<table><tr><th>Date</th><th>Category</th><th>Description</th><th>Amount (LKR)</th></tr>{rows}</table>
<p><small>Generated by the Personal Finance Helper agent. All amounts in LKR.</small></p>
</body></html>"""

    config.REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    path = config.REPORTS_DIR / f"report_{label}.html"
    path.write_text(html, encoding="utf-8")
    return {
        "ok": True, "message": "Report generated. Open the HTML file in a browser.", "file": str(path),
        "month": f"{start:%B %Y}", "total_lkr": summary["total_lkr"], "top_category": summary["top_category"],
        "over_budget_categories": budgets.get("over_budget_categories", []),
        "warning_categories": budgets.get("warning_categories", []),
        "budget_details": [b for b in budgets["budgets"] if b["status"] != "OK"],
    }
